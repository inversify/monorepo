import { type Dirent } from 'node:fs';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot: string = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);

const migrationsPath: string = join(packageRoot, 'prisma', 'migrations');
const outputPath: string = join(
  packageRoot,
  'src',
  'generated',
  'prisma-migrate',
  'index.ts',
);

async function readMigrations(): Promise<string> {
  const entries: Dirent[] = await readdir(migrationsPath, {
    withFileTypes: true,
  });

  const directories: string[] = entries
    .filter((entry: Dirent): boolean => entry.isDirectory())
    .map((entry: Dirent): string => entry.name)
    .sort();

  const migrations: string[] = await Promise.all(
    directories.map(async (directory: string): Promise<string> =>
      readFile(join(migrationsPath, directory, 'migration.sql'), 'utf-8'),
    ),
  );

  return migrations.join('\n');
}

function buildModule(migrations: string): string {
  return `/* eslint-disable */
// This file is generated by src/scripts/generatePrismaMigrate.ts. DO NOT EDIT.

import Database from 'better-sqlite3';
import { mkdir, rm } from 'node:fs/promises';
import { dirname } from 'node:path';

import { DATABASE_URL } from '../../foundation/db/models/databaseUrl.js';

export const MIGRATIONS: string = ${JSON.stringify(migrations)};

function getDatabasePath(url: string): string {
  return url.startsWith('file:') ? url.slice('file:'.length) : url;
}

/**
 * Drops the database and recreates it applying all the migrations.
 */
export async function resetDb(
  url: string = DATABASE_URL,
): Promise<void> {
  const databasePath: string = getDatabasePath(url);

  await Promise.all(
    ['', '-journal', '-wal', '-shm'].map((suffix: string): Promise<void> =>
      rm(\`\${databasePath}\${suffix}\`, { force: true }),
    ),
  );

  await mkdir(dirname(databasePath), { recursive: true });

  const database: Database.Database = new Database(databasePath);

  try {
    database.pragma('foreign_keys = ON');
    database.exec(MIGRATIONS);
  } finally {
    database.close();
  }
}
`;
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, buildModule(await readMigrations()));
